"""
Pydantic schemas for Candidate Generation and Joint Optimization (Milestone M3).

Matches SPEC.md Section 7:
- Candidate eligibility and structured rejection reasons
- Joint assignment optimization plans
- Soft preference score breakdowns
- Feasible, partial, and infeasible scenario classifications
- Greedy baseline comparison
"""
from __future__ import annotations

import enum
import uuid
from datetime import date
from typing import Any

from pydantic import BaseModel, Field

from app.schemas.rules import RuleValidationResult


class FeasibilityStatusEnum(str, enum.Enum):
    feasible = "feasible"      # 100% of affected occurrences covered
    partial = "partial"        # > 0% and < 100% covered (bottlenecks explained)
    infeasible = "infeasible"  # 0% covered


class SolverStatusEnum(str, enum.Enum):
    optimal = "OPTIMAL"
    feasible = "FEASIBLE"
    infeasible = "INFEASIBLE"
    model_invalid = "MODEL_INVALID"
    unknown = "UNKNOWN"


class CandidateRejection(BaseModel):
    """Structured reason why a candidate faculty member was rejected for an occurrence."""
    faculty_id: uuid.UUID
    faculty_name: str
    rule_id: str = Field(description="Violated constraint ID (e.g. HC-01, HC-03, HC-06, HC-07)")
    reason: str = Field(description="Human-readable explanation of rejection")
    details: dict[str, Any] = Field(default_factory=dict)


class CandidateEligibility(BaseModel):
    """Eligibility status of a candidate faculty member for a specific class occurrence."""
    faculty_id: uuid.UUID
    faculty_name: str
    employee_code: str
    department_code: str
    is_eligible: bool
    rejection_reasons: list[CandidateRejection] = Field(default_factory=list)
    soft_scores: dict[str, float] = Field(
        default_factory=dict,
        description="SP-01 to SP-04 scores if eligible"
    )
    total_soft_score: float = Field(
        default=0.0,
        description="Weighted soft preference score [0.0, 1.0]"
    )


class OccurrenceEligibility(BaseModel):
    """Complete candidate pool analysis for a single class occurrence."""
    occurrence_id: uuid.UUID
    occurrence_date: date
    period_id: uuid.UUID
    period_label: str
    course_code: str
    course_name: str
    section_name: str
    total_candidates_evaluated: int
    eligible_count: int
    eligible_candidates: list[CandidateEligibility] = Field(default_factory=list)
    ineligible_candidates: list[CandidateEligibility] = Field(default_factory=list)


class AssignmentProposal(BaseModel):
    """Specific assignment recommendation for a class occurrence."""
    occurrence_id: uuid.UUID
    occurrence_date: date
    period_id: uuid.UUID
    period_label: str
    period_time_range: str
    course_id: uuid.UUID
    course_code: str
    course_name: str
    section_id: uuid.UUID
    section_name: str
    room_id: uuid.UUID
    room_name: str
    original_faculty_id: uuid.UUID
    original_faculty_name: str
    assigned_faculty_id: uuid.UUID | None = None
    assigned_faculty_name: str | None = None
    is_covered: bool
    uncovered_reason: str | None = None
    soft_score: float = Field(default=0.0, description="Normalized score [0.0, 1.0]")
    score_breakdown: dict[str, float] = Field(
        default_factory=dict,
        description="Contribution of each criterion (SP-01..SP-04)"
    )


class OptimizationPlan(BaseModel):
    """
    Complete proposed replacement schedule generated by CP-SAT or greedy baseline.
    """
    plan_id: str = Field(description="Unique identifier for this alternative (e.g. 'plan_a', 'plan_b')")
    plan_name: str = Field(description="Display title (e.g. 'Optimal Joint Plan (Balanced)')")
    description: str
    solver_type: str = Field(description="'cp_sat' or 'greedy_baseline'")
    solver_status: SolverStatusEnum
    solve_time_ms: float = Field(description="Solver execution time in milliseconds")
    total_occurrences: int
    covered_occurrences: int
    uncovered_count: int
    coverage_percentage: float = Field(description="Percentage of affected classes successfully covered")
    overall_score: float = Field(description="Aggregate normalized quality score [0.0, 100.0]")
    score_breakdown: dict[str, float] = Field(
        default_factory=dict,
        description="Average contribution of SP-01, SP-02, SP-03, SP-04"
    )
    assignments: list[AssignmentProposal] = Field(default_factory=list)
    uncovered_assignments: list[AssignmentProposal] = Field(default_factory=list)
    is_valid: bool = Field(description="True if independently validated with 0 new hard violations")
    validation_result: RuleValidationResult | None = None


class OptimizationRequest(BaseModel):
    """Request payload to solve faculty replacement for a scenario."""
    occurrence_ids: list[uuid.UUID] | None = Field(
        default=None,
        description="Specific class occurrence IDs to resolve. If omitted, resolved via faculty_id and dates."
    )
    faculty_id: uuid.UUID | None = Field(
        default=None,
        description="Faculty member whose classes need replacement (e.g. on leave)"
    )
    start_date: date | None = Field(
        default=None,
        description="Start date for resolving affected classes"
    )
    end_date: date | None = Field(
        default=None,
        description="End date for resolving affected classes"
    )
    weights: dict[str, float] | None = Field(
        default=None,
        description="Optional custom weights for SP-01, SP-02, SP-03, SP-04"
    )
    max_alternatives: int = Field(default=3, ge=1, le=5)


class PlannerResponse(BaseModel):
    """Complete response returned by the optimization planner."""
    scenario_summary: str
    feasible_status: FeasibilityStatusEnum = Field(
        description="'feasible' (100% covered), 'partial' (< 100%), or 'infeasible'"
    )
    total_affected_occurrences: int
    plans: list[OptimizationPlan] = Field(
        default_factory=list,
        description="Up to 3 distinct feasible CP-SAT plans"
    )
    baseline_greedy_plan: OptimizationPlan | None = Field(
        default=None,
        description="Greedy heuristic baseline for algorithmic benchmarking"
    )
    candidate_pool_size: int
    data_label: str = "SYNTHETIC — NOT REAL INSTITUTIONAL DATA"

